def spdx_tokens(expr: str) -> list[str]:
    """The tokens of an SPDX expression. "/" (an old cargo form) is OR."""
    return re.findall(r"\(|\)|[^\s()/]+|/", expr.replace("/", " / "))


def classify(expr: str | None) -> str:
    """The class of an SPDX license expression: the best class of the
    choices of an OR, the worst class of the parts of an AND."""
    if not expr:
        return "unknown"
    tokens = spdx_tokens(expr)
    pos = 0

    def rank(c: str) -> int:
        return CLASSES.index(c)

    def atom() -> str:
        nonlocal pos
        if pos >= len(tokens):
            raise ValueError(expr)
        tok = tokens[pos]
        pos += 1
        if tok == "(":
            c = disjunction()
            if pos >= len(tokens) or tokens[pos] != ")":
                raise ValueError(expr)
            pos += 1
            return c
        if pos < len(tokens) and tokens[pos] == "WITH":
            if pos + 1 >= len(tokens) or tokens[pos + 1] not in EXCEPTIONS:
                pos += 2
                return "unknown"
            pos += 2
        if tok in PERMISSIVE or tok == "LicenseRef-BSD-classifier":
            return "permissive"
        if tok in WEAK_COPYLEFT:
            return "weak_copyleft"
        if tok in STRONG_COPYLEFT:
            return "strong_copyleft"
        return "unknown"

    def conjunction() -> str:
        nonlocal pos
        c = atom()
        while pos < len(tokens) and tokens[pos] == "AND":
            pos += 1
            c = max(c, atom(), key=rank)
        return c

    def disjunction() -> str:
        nonlocal pos
        c = conjunction()
        while pos < len(tokens) and tokens[pos] in ("OR", "/"):
            pos += 1
            c = min(c, conjunction(), key=rank)
        return c

    try:
        c = disjunction()
    except ValueError:
        return "unknown"
    return c if pos == len(tokens) else "unknown"


def names_non_permissive(expr: str | None) -> list[str]:
    """The license ids of an expression that are not permissive."""
    if not expr:
        return []
    ids = [
        t
        for t in spdx_tokens(expr)
        if t not in ("(", ")", "AND", "OR", "WITH", "/") and t not in EXCEPTIONS
    ]
    return sorted({t for t in ids if classify(t) != "permissive"})


def python_license(row: dict) -> tuple[str | None, str]:
    """The SPDX expression of a Python package and the metadata field that
    gives it."""
    if row["license_expression"]:
        return row["license_expression"], "License-Expression"
    if row["license_field"] in PY_LICENSE_TEXT:
        return PY_LICENSE_TEXT[row["license_field"]], "License"
    found = [
        PY_CLASSIFIERS[c] for c in row["license_classifiers"] if c in PY_CLASSIFIERS
    ]
    if len(found) == 1:
        return found[0], "Classifier"
    return None, "none"


def license_table(rows: list[dict], key: str = "license") -> dict:
    third = [r for r in rows if not r.get("own")]
    by_license = Counter(r[key] or "(none)" for r in third)
    by_class = Counter(classify(r[key]) for r in third)
    return {
        "packages": len(third),
        "by_license": dict(sorted(by_license.items(), key=lambda kv: (-kv[1], kv[0]))),
        "by_class": {c: by_class.get(c, 0) for c in CLASSES},
        "not_permissive": [
            {
                "name": r["name"],
                "version": r["version"],
                "license": r[key],
                "class": classify(r[key]),
            }
            for r in third
            if classify(r[key]) != "permissive"
        ],
        "permissive_choice_over": [
            {
                "name": r["name"],
                "version": r["version"],
                "license": r[key],
                "not_chosen": names_non_permissive(r[key]),
            }
            for r in third
            if classify(r[key]) == "permissive" and names_non_permissive(r[key])
        ],
        "with_notice_file": [
            {
                "name": r["name"],
                "version": r["version"],
                "license": r[key],
                "files": [
                    f for f in r["license_like_files"] if f.lower().startswith("notice")
                ],
            }
            for r in third
            if any(f.lower().startswith("notice") for f in r["license_like_files"])
        ],
        "apache_only": [
            f"{r['name']} {r['version']}"
            for r in third
            if r[key]
            and classify(r[key]) == "permissive"
            and set(spdx_tokens(r[key])) & {"Apache-2.0"}
            and not set(spdx_tokens(r[key])) & {"OR", "/"}
        ],
    }


