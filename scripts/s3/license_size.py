# collect: sqruff crates


def read_crate_bytes(path: Path) -> dict[str, bytes]:
    """Return {path below the crate folder: bytes} of a .crate archive."""
    out = {}
    with tarfile.open(fileobj=io.BytesIO(gzip.decompress(path.read_bytes()))) as tar:
        for member in tar.getmembers():
            if member.isfile():
                out[member.name.split("/", 1)[1]] = tar.extractfile(member).read()
    return out


def part_of(path: str) -> str:
    first = path.split("/", 1)[0]
    if first in PARTS:
        return first
    return path if "/" not in path else first


def is_generated(data: bytes) -> bool:
    head = b"\n".join(data.splitlines()[:3]).decode("utf8", "replace")
    return bool(GENERATED_MARK.search(head))


def rust_size(files: dict[str, bytes]) -> dict:
    """The .rs files and lines of a crate by kind (hand_written, generated)
    and part (src, tests, benches, examples, or the file), and the
    hand-written src lines by folder below src."""
    out = {
        kind: {"files": 0, "lines": 0, "by_part": {}}
        for kind in ("hand_written", "generated")
    }
    by_dir: Counter = Counter()
    generated = []
    for path in sorted(files):
        if not path.endswith(".rs"):
            continue
        data = files[path]
        kind = "generated" if is_generated(data) else "hand_written"
        n = line_count(data)
        slot = out[kind]["by_part"].setdefault(part_of(path), {"files": 0, "lines": 0})
        slot["files"] += 1
        slot["lines"] += n
        out[kind]["files"] += 1
        out[kind]["lines"] += n
        if kind == "generated":
            first = data.splitlines()[0].decode("utf8", "replace")
            generated.append({"path": path, "lines": n, "first_line": short(first)})
        elif path.startswith("src/"):
            parts = path.split("/")
            by_dir["src/" + parts[1] if len(parts) > 2 else "src/*.rs"] += n
    for kind in out.values():
        kind["by_part"] = dict(sorted(kind["by_part"].items()))
    out["generated_files"] = generated
    out["hand_written_src_by_dir"] = dict(sorted(by_dir.items()))
    return out


def fixture_hashes() -> dict[str, set[str]]:
    """{sha256: the file names} of the non-empty files of the sqlfluff 4.4.0
    test fixtures."""
    base = SQLFLUFF_ROOT / "test" / "fixtures"
    out: dict[str, set[str]] = {}
    for p in base.rglob("*"):
        if p.is_file() and p.stat().st_size:
            out.setdefault(sha256_bytes(p.read_bytes()), set()).add(p.name)
    return out


def data_size(files: dict[str, bytes], sqlfluff_hashes: dict[str, set[str]]) -> dict:
    """The files that are not Rust and not the crate manifest, by top folder.
    equal_to_sqlfluff: the non-empty files that are byte-equal to a file of
    the sqlfluff 4.4.0 test fixtures; same_name: also with the same file
    name."""
    skip = {"Cargo.toml", "Cargo.toml.orig", "Cargo.lock", ".cargo_vcs_info.json"}
    out: dict[str, dict] = {}
    for path, data in sorted(files.items()):
        if path.endswith(".rs") or path in skip:
            continue
        top = path.split("/", 1)[0] if "/" in path else path
        slot = out.setdefault(
            top, {"files": 0, "bytes": 0, "equal_to_sqlfluff": 0, "same_name": 0}
        )
        slot["files"] += 1
        slot["bytes"] += len(data)
        names = sqlfluff_hashes.get(sha256_bytes(data)) if data else None
        if names:
            slot["equal_to_sqlfluff"] += 1
            slot["same_name"] += path.rsplit("/", 1)[-1] in names
    return out


def port_mentions(files: dict[str, bytes]) -> list[dict]:
    """The comment lines of the .rs files that name sqlfluff and say that
    the code is ported, copied, or generated from it."""
    out = []
    for path in sorted(files):
        if not path.endswith(".rs"):
            continue
        for no, line in enumerate(files[path].decode("utf8").splitlines(), 1):
            stripped = line.strip()
            if not stripped.startswith("//"):
                continue
            if "sqlfluff" in stripped.lower() and PORT_MENTION.search(stripped):
                out.append({"file": path, "line": no, "text": short(stripped)})
    return out


def sqruff_structure(contents: dict[str, dict[str, bytes]]) -> dict:
    def text(crate: str, path: str) -> str:
        return contents[crate][path].decode("utf8")

    dialects = contents["sqruff-lib-dialects"]
    dialect_files = sorted(
        p
        for p in dialects
        if re.fullmatch(r"src/[a-z0-9_]+\.rs", p)
        and p != "src/lib.rs"
        and not p.endswith("_keywords.rs")
    )
    keyword_files = sorted(p for p in dialects if p.endswith("_keywords.rs"))
    matchers = sum(
        text("sqruff-lib-dialects", p).count("NodeMatcher::new(") for p in dialect_files
    )
    syntax = text("sqruff-lib-core", "src/dialects/syntax.rs")
    body = syntax.split("pub enum SyntaxKind {", 1)[1].split("\n}", 1)[0]
    kinds = re.findall(r"^\s+([A-Z][A-Za-z0-9]*),\s*$", body, re.M)
    lib = contents["sqruff-lib"]
    rule_files = sorted(
        p for p in lib if re.fullmatch(r"src/rules/[a-z_]+/[a-z]{2}\d{2}\.rs", p)
    )
    rule_kinds = sum(text("sqruff-lib", p).count("SyntaxKind::") for p in rule_files)
    rule_impls = sum(
        len(re.findall(r"^impl(?:<[^>]*>)? Rule for ", text("sqruff-lib", p), re.M))
        for p in rule_files
    )
    trait = re.search(
        r"^pub trait Rule\b.*$", text("sqruff-lib", "src/core/rules.rs"), re.M
    )
    return {
        "dialect_modules": [p.removeprefix("src/") for p in dialect_files],
        "keyword_modules": len(keyword_files),
        "node_matchers_in_dialect_modules": matchers,
        "syntax_kind_variants": len(kinds),
        "rule_files": len(rule_files),
        "rule_files_impl_rule": rule_impls,
        "syntax_kind_uses_in_rule_files": rule_kinds,
        "rule_trait": trait[0] if trait else None,
        "rule_lines": sum(line_count(lib[p]) for p in rule_files),
    }


def sqruff_crates(
    cache: Path, sqlfluff_hashes: dict[str, set[str]]
) -> tuple[dict, dict]:
    contents = {}
    meta = {}
    for name in SQRUFF_CRATES:
        path = cache / f"{name}-{SQRUFF_VERSION}.crate"
        if not path.exists():
            raise DataError(f"{path} does not exist; run tools/sqruff/install.sh")
        contents[name] = read_crate_bytes(path)
        meta[name] = sha256_bytes(path.read_bytes())
    locked = lock_checksums(contents["sqruff"]["Cargo.lock"].decode("utf8"))
    out = {}
    for name in SQRUFF_CRATES:
        files = contents[name]
        if name != "sqruff" and locked.get(f"{name}-{SQRUFF_VERSION}") != meta[name]:
            raise DataError(
                f"{name}: the crate is not the one of the sqruff Cargo.lock"
            )
        vcs = json.loads(files[".cargo_vcs_info.json"])
        manifest = files["Cargo.toml"].decode("utf8")
        lic = re.search(r'^license = "([^"]+)"', manifest, re.M)
        out[name] = {
            "sha256": meta[name],
            "source": "crates.io",
            "vcs_commit": vcs["git"]["sha1"],
            "path_in_vcs": vcs["path_in_vcs"],
            "cargo_license": lic[1] if lic else None,
            "license_like_files": sorted(
                p for p in files if LICENSE_NAME.match(p.rsplit("/", 1)[-1])
            ),
            "files": len(files),
            "rust": rust_size(files),
            "data": data_size(files, sqlfluff_hashes),
            "sqlfluff_port_mentions": port_mentions(files),
        }
    return out, sqruff_structure(contents)


def lock_checksums(lock: str) -> dict[str, str]:
    out = {}
    for block in lock.split("[[package]]"):
        name = re.search(r'^name = "([^"]+)"', block, re.M)
        version = re.search(r'^version = "([^"]+)"', block, re.M)
        checksum = re.search(r'^checksum = "([0-9a-f]+)"', block, re.M)
        if name and version and checksum:
            out[f"{name[1]}-{version[1]}"] = checksum[1]
    return out


