# collect: the sqlfluff history. The submodule is a shallow clone and does
# not have it.


def sqlfluff_clone(st: probe.Steps, scratch: Path) -> Path:
    repo = scratch / "sqlfluff-history.git"
    st.run(
        "clone sqlfluff (all commits, no trees)",
        ["git", "clone", "--quiet", "--bare", "--filter=tree:0", SQLFLUFF_REPO, repo],
        scratch,
    )
    return repo


def sqlfluff_history(st: probe.Steps, repo: Path, sha: str, pin: str) -> dict:
    """The place of commit sha in the history of commit pin. Fail if repo is
    shallow or does not have the two commits."""
    shallow = st.run(
        "shallow check", ["git", "rev-parse", "--is-shallow-repository"], repo
    ).stdout.strip()
    if shallow != "false":
        raise DataError(f"{repo} is a shallow clone; it has no full history")
    for commit in (sha, pin):
        found = st.run(
            "commit check",
            ["git", "rev-parse", "--verify", "--quiet", f"{commit}^{{commit}}"],
            repo,
            check=False,
        )
        if found.returncode != 0 or found.stdout.strip() != commit:
            raise DataError(f"{repo} does not have the commit {commit}")
    ancestor = st.run(
        "is .sqlfluff-sha an ancestor of the pin",
        ["git", "merge-base", "--is-ancestor", sha, pin],
        repo,
        check=False,
    ).returncode
    if ancestor not in (0, 1):
        raise DataError(f"git merge-base --is-ancestor: exit code {ancestor}")
    left, right = map(
        int,
        st.run(
            "commits only in .sqlfluff-sha, only in the pin",
            ["git", "rev-list", "--left-right", "--count", f"{sha}...{pin}"],
            repo,
        ).stdout.split(),
    )
    if (ancestor == 0) != (left == 0):
        raise DataError("merge-base and rev-list do not agree")
    dates = st.run(
        "commit dates", ["git", "show", "-s", "--format=%cI", sha, pin], repo
    ).stdout.split()
    return {
        "repository": SQLFLUFF_REPO,
        "pin": pin,
        "commits_only_in_sqlfluff_sha": left,
        "commits_only_in_pin": right,
        "is_ancestor_of_pin": ancestor == 0,
        "sqlfluff_sha_date": dates[0],
        "pin_date": dates[1],
    }


# collect: the sqruff repository at the tag


def sqruff_repo(st: probe.Steps, scratch: Path, commits: set[str]) -> dict:
    repo = scratch / "sqruff"
    st.run(
        "clone sqruff",
        [
            "git",
            "clone",
            "--quiet",
            "--filter=blob:none",
            "--no-checkout",
            SQRUFF_REPO,
            repo,
        ],
        scratch,
    )
    commit = st.run(
        "sqruff tag commit", ["git", "rev-parse", f"{SQRUFF_TAG}^{{commit}}"], repo
    ).stdout.strip()
    if {commit} != commits:
        raise DataError(
            f"{SQRUFF_TAG} is {commit}, the crates are of {sorted(commits)}"
        )
    st.run("check out the tag", ["git", "checkout", "--quiet", commit], repo)
    names = st.run("tracked files", ["git", "ls-files", "-z"], repo).stdout.split("\0")
    names = sorted(n for n in names if n)
    licenses = [
        license_file(n, (repo / n).read_bytes())
        for n in names
        if LICENSE_NAME.match(n.rsplit("/", 1)[-1])
    ]
    grants = []
    for n in names:
        data = (repo / n).read_bytes()
        try:
            text = data.decode("utf8")
        except UnicodeDecodeError:
            continue
        if MIT_GRANT in text:
            grants.append({"path": n, "copyright": copyright_lines(text)})
    sha_file = repo / ".sqlfluff-sha"
    sqlfluff_sha = sha_file.read_text("utf8").strip() if sha_file.exists() else None
    history = None
    if sqlfluff_sha:
        history = sqlfluff_history(
            st, sqlfluff_clone(st, scratch), sqlfluff_sha, sqlfluff_ref(SQLFLUFF_ROOT)
        )
    workspace = (repo / "Cargo.toml").read_text("utf8")
    lic = re.search(r'^license = "([^"]+)"', workspace, re.M)
    return {
        "url": SQRUFF_REPO,
        "tag": SQRUFF_TAG,
        "commit": commit,
        "workspace_license": lic[1] if lic else None,
        "license_files": licenses,
        "files_with_mit_grant": grants,
        "sqlfluff_sha": sqlfluff_sha,
        "sqlfluff_sha_history": history,
    }


# collect: dependencies


def tree_packages(text: str) -> list[dict]:
    out = {}
    for line in text.splitlines():
        if not line.strip():
            continue
        # cargo tree adds " (*)" after the format of a package that it
        # showed before.
        spec, _, lic = line.removesuffix(" (*)").partition("|")
        m = TREE_LINE.match(spec.strip())
        if not m:
            raise DataError(f"cargo tree line: {line!r}")
        out[(m[1], m[2])] = {"name": m[1], "version": m[2], "tree_license": lic or None}
    return [out[k] for k in sorted(out)]


def crate_license_files(manifest: str) -> list[str]:
    folder = Path(manifest).parent
    return sorted(
        p.name for p in folder.iterdir() if p.is_file() and LICENSE_NAME.match(p.name)
    )


def dependencies(st: probe.Steps, cwd: Path, profiles: dict, own: set[str]) -> dict:
    meta_proc = st.run(
        "cargo metadata",
        ["cargo", "metadata", "--locked", "--all-features", "--format-version", "1"],
        cwd,
    )
    meta = json.loads(meta_proc.stdout)
    by_key = {(p["name"], p["version"]): p for p in meta["packages"]}
    out = {}
    for name, prof in profiles.items():
        proc = st.run(f"cargo tree ({name})", ["cargo", *TREE_ARGS, *prof["args"]], cwd)
        rows = []
        for pkg in tree_packages(proc.stdout):
            m = by_key.get((pkg["name"], pkg["version"]))
            if m is None:
                raise DataError(
                    f"{pkg['name']} {pkg['version']} is not in cargo metadata"
                )
            if (m["license"] or None) != pkg["tree_license"]:
                raise DataError(
                    f"{pkg['name']}: cargo tree and cargo metadata disagree"
                )
            source = m["source"] or "path"
            rows.append(
                {
                    "name": pkg["name"],
                    "version": pkg["version"],
                    "license": m["license"],
                    "license_file": m["license_file"],
                    "license_like_files": crate_license_files(m["manifest_path"]),
                    "source": "crates.io" if source.startswith("registry+") else source,
                    "own": pkg["name"] in own,
                }
            )
        out[name] = {
            "what": prof["what"],
            "command": " ".join(["cargo", *TREE_ARGS, *prof["args"]]),
            "packages": rows,
        }
    return out


# collect: sqlfluffrs and sqlfluff


def sqlfluffrs_structure(workspace: Path) -> dict:
    rules = sorted(
        p.name
        for p in (workspace / "sqlfluffrs_rules" / "src").glob("*.rs")
        if re.fullmatch(r"[a-z]{2}\d{2}\.rs", p.name)
    )
    arena = (workspace / "sqlfluffrs_parser" / "src" / "parser" / "arena.rs").read_text(
        "utf8"
    )
    is_type = re.search(r"^\s*pub fn is_type\(.*$", arena, re.M)
    dialect_dir = workspace / "sqlfluffrs_dialects" / "src" / "dialect"
    per_dialect = {
        d.name: sorted(f.name for f in d.iterdir() if f.is_file())
        for d in sorted(dialect_dir.iterdir())
        if d.is_dir()
    }
    files = Counter(tuple(v) for v in per_dialect.values())
    return {
        "rule_modules": rules,
        "arena_is_type": is_type[0].strip() if is_type else None,
        "generated_dialects": len(per_dialect),
        "generated_files_per_dialect": [
            {"files": list(k), "dialects": n} for k, n in files.most_common()
        ],
    }


def python_lines(sub: Path, tracked: set[str]) -> dict:
    out = {}
    for part, folder in SQLFLUFF_PARTS.items():
        files = sorted(
            p for p in tracked if p.startswith(folder + "/") and p.endswith(".py")
        )
        out[part] = {
            "folder": folder,
            "files": len(files),
            "lines": sum(line_count((sub / p).read_bytes()) for p in files),
        }
    dialect_files = [
        p for p in tracked if re.fullmatch(r"src/sqlfluff/dialects/dialect_\w+\.py", p)
    ]
    out["dialects"]["dialect_modules"] = len(dialect_files)
