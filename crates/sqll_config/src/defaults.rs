//! The sqlfluff default config. The test `the_defaults_are_those_of_the_
//! pinned_sqlfluff` (tests/defaults.rs) reads `default_config.cfg` of the
//! submodule and compares each value.

use std::sync::OnceLock;

use crate::dict::records_to_nested_dict;
use crate::value::{Table, Value};

/// A default value. The default config has no float.
#[derive(Clone, Copy, Debug)]
pub enum D {
    None,
    Bool(bool),
    Int(i64),
    Str(&'static str),
}

impl D {
    pub fn value(self) -> Value {
        match self {
            D::None => Value::None,
            D::Bool(b) => Value::Bool(b),
            D::Int(i) => Value::Int(i),
            D::Str(s) => Value::Str(s.to_string()),
        }
    }
}

